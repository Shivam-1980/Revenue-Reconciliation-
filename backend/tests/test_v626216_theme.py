"""Dark mode wiring: theme set before first paint, a three-way control in the header, and a generated dark layer."""
from pathlib import Path

FRONTEND = Path(__file__).resolve().parents[2] / "frontend"


def _read(rel):
    return (FRONTEND / rel).read_text(encoding="utf-8")


def test_theme_is_applied_before_first_paint_and_survives_blocked_storage():
    html = _read("index.html")
    assert 'setAttribute("data-theme"' in html and "eko.ui.theme" in html and "try {" in html
    assert html.index('setAttribute("data-theme"') < html.index('src="/src/main.jsx"')


def test_header_has_the_light_dark_system_control():
    main, ux = _read("src/main.jsx"), _read("src/ux.jsx")
    assert 'import "./dark.css"' in main and "<ThemeControl theme={theme}/>" in main
    assert '"light", "dark", "system"' in ux and "prefers-color-scheme: dark" in ux


def test_dark_layer_covers_the_stylesheets_and_is_not_hand_edited():
    dark = _read("src/dark.css")
    assert dark.startswith("/* GENERATED by scripts/gen-dark.mjs")
    for selector in (".rr-card{", ".card{", ".auth-sso", "table"):
        assert f':root[data-theme="dark"] {selector}' in dark or selector in dark
    assert dark.count(':root[data-theme="dark"]') > 300
