// Builds src/dark.css: for every colour in styles.css/theme.css, a dark-theme override rule.
// The light stylesheets stay untouched; run `node scripts/gen-dark.mjs` after changing them.
import fs from "node:fs";
import postcss from "postcss";

const SRC = ["src/styles.css", "src/theme.css"];
const PREFIX = ':root[data-theme="dark"]';

const clamp = (v, a = 0, b = 1) => Math.min(b, Math.max(a, v));
function rgb2hsl(r, g, b) {
  r /= 255; g /= 255; b /= 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2, d = max - min;
  if (!d) return [0, 0, l];
  const s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
  const h = max === r ? ((g - b) / d + (g < b ? 6 : 0)) : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
  return [h * 60, s, l];
}
function hsl2rgb(h, s, l) {
  const c = (1 - Math.abs(2 * l - 1)) * s, x = c * (1 - Math.abs(((h / 60) % 2) - 1)), m = l - c / 2;
  const [r, g, b] = h < 60 ? [c, x, 0] : h < 120 ? [x, c, 0] : h < 180 ? [0, c, x] : h < 240 ? [0, x, c] : h < 300 ? [x, 0, c] : [c, 0, x];
  return [r + m, g + m, b + m].map((v) => Math.round(clamp(v) * 255));
}
function parseColor(tok) {
  tok = tok.trim().toLowerCase();
  let m;
  if ((m = /^#([0-9a-f]{3,8})$/.exec(tok))) {
    let h = m[1];
    if (h.length === 3 || h.length === 4) h = [...h].map((c) => c + c).join("");
    if (h.length !== 6 && h.length !== 8) return null;
    return { r: parseInt(h.slice(0, 2), 16), g: parseInt(h.slice(2, 4), 16), b: parseInt(h.slice(4, 6), 16), a: h.length === 8 ? parseInt(h.slice(6), 16) / 255 : 1 };
  }
  if ((m = /^rgba?\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*(?:,\s*([\d.]+)\s*)?\)$/.exec(tok))) return { r: +m[1], g: +m[2], b: +m[3], a: m[4] === undefined ? 1 : +m[4] };
  return null;
}
const out = (r, g, b, a) => a < 1 ? `rgba(${r},${g},${b},${+a.toFixed(3)})` : "#" + [r, g, b].map((v) => v.toString(16).padStart(2, "0")).join("");

// kind: "bg" | "text" | "border"
function remap(c, kind) {
  let [h, s, l] = rgb2hsl(c.r, c.g, c.b);
  if (s < 0.05) { h = 215; s = 0.3; }                              // neutral surfaces get the same cool tint as the rest
  let nl = l, ns = s;
  if (kind === "bg") {
    if (c.a <= 0.5 && l > 0.8) return c;                          // translucent white overlays belong to dark panels
    if (l >= 0.8) { nl = 0.08 + (1 - l) * 0.9; ns = s * 0.5; } else return c;
  } else if (kind === "border") {
    if (l >= 0.7) { nl = 0.15 + (1 - l) * 0.45; ns = s * 0.4; } else return c;
  } else {
    if (l >= 0.85) return c;                                      // white text sits on a coloured fill
    if (l < 0.65) { nl = 0.93 - l * 0.55; ns = s * 0.75; } else return c;
  }
  const [r, g, b] = hsl2rgb(h, ns, nl);
  return { r, g, b, a: c.a };
}

const kindOf = (prop) => {
  if (/^(background|background-color|background-image)$/.test(prop)) return "bg";
  if (/^(border|outline|column-rule)(-|$)/.test(prop) || prop === "border" || prop === "outline") return "border";
  if (/^(color|fill|stroke|caret-color|-webkit-text-fill-color|text-decoration|text-decoration-color)$/.test(prop)) return "text";
  if (prop.startsWith("--")) return /line|hairline/.test(prop) ? "border" : /surface|soft|canvas|bg|hover/.test(prop) ? "bg" : /ink|text|muted/.test(prop) ? "text" : null;
  return null;
};

const COLOR_RE = /#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)/g;
function convert(value, kind) {
  let changed = false;
  const v = value.replace(COLOR_RE, (tok) => {
    const c = parseColor(tok);
    if (!c) return tok;
    const n = remap(c, kind);
    if (n === c) return tok;
    changed = true;
    return out(n.r, n.g, n.b, n.a);
  });
  return changed ? v : null;
}

const prefixSelector = (sel) => {
  sel = sel.trim();
  if (sel.startsWith(":root")) return PREFIX + sel.slice(5);
  if (sel === "html") return "html" + '[data-theme="dark"]';
  return `${PREFIX} ${sel}`;
};

const lines = [];
function walk(container, wrap) {
  container.each((node) => {
    if (node.type === "atrule") {
      if (/keyframes|font-face|import|tailwind|layer|charset/i.test(node.name)) return;
      const inner = [];
      walk(node, inner);
      if (inner.length) wrap.push(`@${node.name} ${node.params}{\n${inner.join("\n")}\n}`);
    } else if (node.type === "rule") {
      const decls = [];
      node.walkDecls((d) => {
        if (d.parent !== node) return;
        const k = kindOf(d.prop);
        if (!k) return;
        const nv = convert(d.value, k);
        if (nv !== null) decls.push(`${d.prop}:${nv}${d.important ? "!important" : ""}`);
      });
      if (decls.length) wrap.push(`${node.selectors.map(prefixSelector).join(",")}{${decls.join(";")}}`);
    }
  });
}
for (const f of SRC) {
  const root = postcss.parse(fs.readFileSync(f, "utf8"));
  lines.push(`/* from ${f} */`);
  walk(root, lines);
}

const header = `/* GENERATED by scripts/gen-dark.mjs from styles.css + theme.css: do not edit the generated rules, edit the generator. */\n`;
const footer = fs.readFileSync("scripts/dark-extra.css", "utf8");
fs.writeFileSync("src/dark.css", header + lines.join("\n") + "\n" + footer);
console.log("dark.css rules:", lines.length);
